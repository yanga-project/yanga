PYTEST_FRAMEWORK = "pytest"


@dataclass
class PytestCMakeGeneratorConfig(DataClassDictMixin):
    #: Mocking configuration
    mocking: MockingConfig | None = None


class PytestBindingCreator(CMakeMockupCreator):
    """Runs ``clanguru bind`` on the partial link of a test scope: a ctypes binding and C mocks for what stays undefined."""

    def __init__(
        self,
        name: str,
        sources: list[Path],
        build_dir: CMakePath,
        object_library_targets: list[str],
        artifacts_locator: CMakeArtifactsLocator,
        mocking_config: MockingConfig | None,
    ) -> None:
        super().__init__(f"{name}_pytest", sources, build_dir, object_library_targets, f"{name}_pytest_binding", artifacts_locator, mocking_config)
        self.binding_name = f"{name}_binding"

    def get_clanguru_arguments(self) -> list[str]:
        return ["bind", "--filename", self.binding_name, "--library-name", self.name]

    def get_mockup_generated_files(self) -> list[CMakePath]:
        return [self.build_dir.joinpath(f"{self.binding_name}.py"), *self.get_mockup_sources(), self.build_dir.joinpath(f"{self.binding_name}.log")]

    def get_mockup_sources(self) -> list[CMakePath]:
        return [self.build_dir.joinpath(f"{self.binding_name}_mocks.c")]


class PytestCMakeGenerator(CMakeGenerator):
    """
    Builds a shared test library per pytest scope: a component, an integration component and the variant.

    List it after the ``GTestCMakeGenerator`` and before the ``TestResultsCMakeGenerator``.
    """

    def __init__(self, execution_context: ExecutionContext, output_dir: Path, config: dict[str, Any] | None = None) -> None:
        super().__init__(execution_context, output_dir, config)
        self.artifacts_locator = CMakeArtifactsLocator(output_dir, execution_context.spl_paths)

    @cached_property
    def config_obj(self) -> PytestCMakeGeneratorConfig:
        return PytestCMakeGeneratorConfig.from_dict(self.config) if self.config else PytestCMakeGeneratorConfig()

    def generate(self) -> list[CMakeElement]:
        if importlib.util.find_spec(PYTEST_FRAMEWORK) is None:
            raise UserNotificationException(f"{PYTEST_FRAMEWORK} is not installed in {sys.executable}: add it to the project's Python dependencies.")
        elements: list[CMakeElement] = [CMakeComment(f"Generated by {self.__class__.__name__}")]
        for component in self.execution_context.components:
            # A container compiles nothing itself.
            if component.is_container:
                continue
            build_dir = self.artifacts_locator.get_component_build_dir(component.name)
            object_library = CMakeAddLibrary(f"{component.name}_pytest_PC", component.sources, compile_options=["-ggdb", "--coverage"], component_name=component.name)
            include_dirs = [build_dir, *GTestCMakeComponent(component, self.execution_context).get_include_directories()]
            elements.extend(
                [
                    object_library,
                    CMakeSetTargetProperties(object_library.target_name, {"POSITION_INDEPENDENT_CODE": "ON"}),
                    CMakeTargetIncludeDirectories(object_library.target_name, include_dirs, IncludeScope.PRIVATE if component.sources else IncludeScope.INTERFACE),
                ]
            )
            testing_block = find_testing_block(component.testing, PYTEST_FRAMEWORK)
            if testing_block and testing_block.sources:
                if not component.sources:
                    raise UserNotificationException(f"Component '{component.name}' has no sources: a {PYTEST_FRAMEWORK} test scope needs C sources.")
                elements.extend(self.create_test_library(component.name, component.sources, build_dir, [object_library.target_name], testing_block, include_dirs, component.name))
        elements.extend(self.create_variant_test_library())
        return elements

    def create_variant_test_library(self) -> list[CMakeElement]:
        """Link the objects of the components the variant ships, as the gtest variant test does."""
        testing_block = find_testing_block(self.execution_context.variant_testing, PYTEST_FRAMEWORK)
        if not (testing_block and testing_block.sources):
            return []
        components = variant_test_components(self.execution_context.components)
        registry_dirs = collect_directories(filter_artifacts(self.execution_context.data_registry.find_data(Artifact), with_label("include"), for_consumer()))
        build_dir = self.artifacts_locator.cmake_build_dir.joinpath(VARIANT_TEST_NAME)
        include_dirs = [build_dir, *[CMakePath(path) for path in resolve_include_directories(self.execution_context.components) + registry_dirs]]
        return self.create_test_library(
            str(self.execution_context.variant_name),
            [source for component in components for source in component.sources],
            build_dir,
            [f"{component.name}_pytest_PC_lib" for component in components if component.sources],
            testing_block,
            include_dirs,
            component_name=None,
        )

    def create_test_library(
        self,
        name: str,
        sources: list[Path],
        build_dir: CMakePath,
        object_libraries: list[str],
        testing_block: TestingBlock,
        include_dirs: list[CMakePath],
        component_name: str | None,
    ) -> list[CMakeElement]:
        elements: list[CMakeElement] = []
        libraries = list(object_libraries)
        if testing_block.mockup_sources:
            mockup_library = create_mockup_library(f"{name}_pytest_mockups", testing_block.mockup_sources, component_name)
            elements.extend(
                [
                    mockup_library,
                    CMakeSetTargetProperties(mockup_library.target_name, {"POSITION_INDEPENDENT_CODE": "ON"}),
                    CMakeTargetIncludeDirectories(mockup_library.target_name, include_dirs),
                ]
            )
            libraries.append(mockup_library.target_name)
        binding_creator = PytestBindingCreator(name, sources, build_dir, libraries, self.artifacts_locator, self.mocking_config(testing_block))
        elements.extend(binding_creator.generate())
        shared_library = CMakeAddLibrary(
            f"{name}_pytest",
            [source.to_path() for source in binding_creator.get_mockup_sources()],
            LibraryType.SHARED,
            compile_options=NO_COVERAGE_OPTIONS,
            component_name=component_name,
        )
        elements.extend(
            [
                shared_library,
                # -z,defs: a symbol neither bound nor mocked fails the link on Linux, not the import in pytest.
                CMakeTargetLinkLibraries(shared_library.target_name, [*libraries, "--coverage", "$<$<PLATFORM_ID:Linux>:-Wl,-z,defs>"]),
                CMakeSetTargetProperties(
                    shared_library.target_name,
                    {
                        "OUTPUT_NAME": f"{name}_pytest",
                        "PREFIX": '""',
                        # A DLL exports nothing unless asked; .so and .dylib export by default.
                        "WINDOWS_EXPORT_ALL_SYMBOLS": "ON",
                        "LIBRARY_OUTPUT_DIRECTORY": build_dir,
                        "RUNTIME_OUTPUT_DIRECTORY": build_dir,
                    },
                ),
                CMakeTargetIncludeDirectories(shared_library.target_name, include_dirs),
            ]
        )
        # The variant test runs with GCOV_PREFIX, so its .gcda files do not mix into the coverage of the component tests.
        gcov_dir = None if component_name else build_dir.joinpath("pytest_gcov")
        junit_report = build_dir.joinpath(f"{name}_pytest_junit.xml")
        test_files = [CMakePath(source) for source in testing_block.sources]
        execute_tests_command = CMakeCustomCommand(
            "Run pytest, generate JUnit report and return success independent of the test result",
            outputs=[junit_report],
            depends=[shared_library.target_name, build_dir.joinpath(f"{binding_creator.binding_name}.py"), *test_files],
            commands=[
                CMakeCommand(
                    "${CMAKE_COMMAND}",
                    [
                        "-E",
                        "env",
                        f"PYTHONPATH={build_dir}",
                        *([f"GCOV_PREFIX={gcov_dir}"] if gcov_dir else []),
                        Path(sys.executable).as_posix(),
                        "-m",
                        "pytest",
                        "-p",
                        "no:cacheprovider",
                        f"--junitxml={junit_report}",
                        *test_files,
                        "||",
                        "${CMAKE_COMMAND}",
                        "-E",
                        "true",
                    ],
                )
            ],
            working_directory=CMakePath(self.execution_context.project_root_dir),
        )
        if component_name:
            test_target = UserRequest(UserRequestScope.COMPONENT, component_name=component_name, target=f"{PYTEST_FRAMEWORK}_test")
            coverage_target = UserRequest(UserRequestScope.COMPONENT, component_name=component_name, target=UserRequestTarget.COVERAGE)
        else:
            test_target = UserRequest(UserRequestScope.VARIANT, target=f"variant_{PYTEST_FRAMEWORK}_test")
            coverage_target = UserRequest(UserRequestScope.VARIANT, target=f"{VARIANT_TEST_NAME}_coverage")
        elements.append(execute_tests_command)
        elements.append(CMakeCustomTarget(test_target.target_name, f"Execute the {PYTEST_FRAMEWORK} tests of {name}", [], [junit_report], True))
        self.execution_context.data_registry.insert(
            TestResultFile(target=test_target, junit_report=junit_report, framework=PYTEST_FRAMEWORK, test_sources=[]),
            test_target.target_name,
        )

        # Generate the coverage tracefile; the collector merges it and builds the reports
        gcovr_config_file = build_dir.joinpath(f"{name}_pytest_gcovr.cfg")
        gcovr_json_file = build_dir.joinpath(f"{name}_pytest_coverage.json")
        elements.append(
            create_coverage_tracefile_command(
                f"Generate the {PYTEST_FRAMEWORK} coverage report for {name}",
                execute_tests_command.outputs,
                object_libraries,
                sources,
                self.execution_context.project_root_dir,
                gcovr_config_file,
                gcovr_json_file,
                gcov_dir,
            )
        )
        self.execution_context.data_registry.insert(
            CoverageRelevantFile(target=coverage_target, json_report=gcovr_json_file, framework=PYTEST_FRAMEWORK),
            coverage_target.target_name,
        )
        return elements

    def mocking_config(self, testing_block: TestingBlock) -> MockingConfig | None:
        """Merge the block's ``config.mocking`` over the platform mocking; the binding needs the mocks, so they cannot be disabled."""
        mocking = merge_block_mocking(self.config_obj.mocking, testing_block)
        if any(config and config.enabled is False for config in (self.config_obj.mocking, mocking)):
            raise UserNotificationException(f"The {PYTEST_FRAMEWORK} test library needs its mocks: remove 'mocking.enabled: false'.")
        return mocking
