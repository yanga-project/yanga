from yanga_core.domain.components import TestingBlock
from yanga_core.domain.execution_context import UserRequest, UserRequestScope, UserRequestTarget
from yanga_core.domain.generated_file import GeneratedFile
from yanga_core.domain.reports import ReportRelevantFiles, ReportRelevantFileType

from .cmake_backend import (
    CMakeAddTargetCleanFiles,
    CMakeCommand,
    CMakeComment,
    CMakeCustomCommand,
    CMakeCustomTarget,
    CMakeElement,
    CMakePath,
    cmake_directory_provider,
)
from .coverage import CoverageArtifactsLocator, CoverageRelevantFile
from .generator import CMakeGenerator, report_level, subcomponent_names
from .sphinx_test_report import TestResultFile, order_by_testing


class TestResultsCMakeGenerator(CMakeGenerator):
    """
    Collect the test results and coverage tracefiles of every test framework into the `test` and `coverage` targets of each level.

    It reads what the test generators registered, so place it after them in the platform generators.
    """

    __test__ = False  # not a pytest test class

    def generate(self) -> list[CMakeElement]:
        elements: list[CMakeElement] = [CMakeComment(f"Generated by {self.__class__.__name__}")]
        test_results = list(self.execution_context.data_registry.find_data(TestResultFile))
        coverage_files = list(self.execution_context.data_registry.find_data(CoverageRelevantFile))
        if not test_results and not coverage_files:
            return elements
        elements.extend(self._test_targets(test_results))
        elements.extend(self._coverage_targets(coverage_files))
        return elements

    def _test_targets(self, test_results: list[TestResultFile]) -> list[CMakeElement]:
        entries: dict[str | None, list[TestResultFile]] = {}
        for test_result in test_results:
            entries.setdefault(test_result.target.component_name, []).append(test_result)
        elements: list[CMakeElement] = []
        for component in self.execution_context.components:
            # A container runs the tests of its subcomponents, recursively
            if component.is_container:
                depends = [
                    UserRequest(UserRequestScope.COMPONENT, component_name=name, target=UserRequestTarget.TEST).target_name
                    for name in subcomponent_names(component)
                    if name in entries
                ]
            elif component.name in entries:
                depends = self._run_targets(entries[component.name], component.testing)
            else:
                continue
            elements.extend(
                CMakeCustomTarget(
                    UserRequest(UserRequestScope.COMPONENT, component_name=component.name, target=target).target_name,
                    f"Execute tests for {component.name}",
                    [],
                    depends,
                    True,
                )
                for target in (UserRequestTarget.TEST, UserRequestTarget.BUILD)
            )
        if None in entries:
            variant_test_target = UserRequest(UserRequestScope.VARIANT, target=UserRequestTarget.TEST)
            depends = self._run_targets(entries[None], self.execution_context.variant_testing)
            elements.append(CMakeCustomTarget(variant_test_target.target_name, f"Execute the variant test of {self.execution_context.variant_name}", [], depends, True))
        return elements

    def _run_targets(self, test_results: list[TestResultFile], testing_blocks: list[TestingBlock]) -> list[str]:
        """In the `testing` order, unlisted frameworks last, like the sections of the test results page."""
        return [test_result.target.target_name for test_result in order_by_testing(test_results, testing_blocks)]

    def _coverage_targets(self, coverage_files: list[CoverageRelevantFile]) -> list[CMakeElement]:
        """
        The coverage report of each entry and the merged ones, built from the tracefiles only.

        Unit and integration counters never mix in the all components report: integration tests count only per
        container, over all containers and overall.
        """
        elements: list[CMakeElement] = []
        artifacts_locator = CoverageArtifactsLocator(self.output_dir, self.execution_context.spl_paths)
        variant_reports_dir = artifacts_locator.cmake_variant_reports_dir
        components = {component.name: component for component in self.execution_context.components}
        entries: dict[str, list[CoverageRelevantFile]] = {}
        for coverage_file in coverage_files:
            entries.setdefault(coverage_file.target.target_name, []).append(coverage_file)
        component_files: dict[str, list[CoverageRelevantFile]] = {}
        for entry_files in entries.values():
            target = entry_files[0].target
            name = target.component_name
            if name is None:
                description = "Generate coverage report for the variant test"
                html_dir = variant_reports_dir.joinpath(target.target_name)
                elements.extend(self._merged_coverage(target, description, description, variant_reports_dir, html_dir, entry_files, [], ["variant", "coverage"]))
            else:
                component_files[name] = entry_files
                elements.extend(
                    self._merged_coverage(
                        target,
                        f"Generate coverage report for component {name}",
                        f"Generate coverage report for {name}",
                        artifacts_locator.get_component_reports_dir(name),
                        artifacts_locator.get_component_coverage_reports_dir(name),
                        entry_files,
                        [],
                        [report_level(components[name]), name, "coverage"],
                    )
                )

        copied_reports = list(component_files)
        container_files: list[CoverageRelevantFile] = []
        for container in (component for component in components.values() if component.is_container):
            subcomponent_files = [coverage_file for name in subcomponent_names(container) for coverage_file in component_files.get(name, [])]
            container_files.extend(subcomponent_files)
            if subcomponent_files:
                copied_reports.append(container.name)
                elements.extend(
                    self._merged_coverage(
                        UserRequest(UserRequestScope.COMPONENT, component_name=container.name, target=UserRequestTarget.COVERAGE),
                        f"Merge coverage for container {container.name}",
                        f"Generate coverage report for container {container.name}",
                        artifacts_locator.get_component_reports_dir(container.name),
                        artifacts_locator.get_component_coverage_reports_dir(container.name),
                        subcomponent_files,
                        [],
                        ["container", container.name, "coverage"],
                    )
                )

        gcovr_html_dir = artifacts_locator.get_variant_coverage_reports_dir()
        # One canonical provider for the variant coverage reports directory. Consumers that write into this dir
        # depend on its stamp; ninja then serializes the make_directory through the dep graph.
        gcovr_html_dir_provider = cmake_directory_provider(gcovr_html_dir)
        elements.append(gcovr_html_dir_provider.command)

        # The html coverage reports are generated in the component specific reports directories.
        # We need to create custom commands to copy them to the variant report directory.
        copy_stamps: list[CMakePath] = []
        component_variant_coverage_html_dirs: list[CMakePath] = []
        for component_name in copied_reports:
            component_coverage_html_dir = artifacts_locator.get_component_coverage_reports_dir(component_name)
            component_variant_coverage_html_dir = artifacts_locator.get_component_variant_coverage_reports_dir(component_name)
            component_variant_coverage_html_dirs.append(component_variant_coverage_html_dir)
            # copy_directory has no canonical file output (it copies an arbitrary tree), so the tracked output is a stamp we touch ourselves.
            # The destination dir is not given a directory provider: only this command writes into it, so there is no race to gate against.
            copy_done_stamp = component_variant_coverage_html_dir.joinpath(".yanga.stamp")
            elements.append(
                CMakeCustomCommand(
                    description=f"Copy coverage html report for component {component_name} to variant report directory",
                    outputs=[copy_done_stamp],
                    # The report file, not the target name: a target name is only an order-only dependency
                    depends=[artifacts_locator.get_component_coverage_html_file(component_name), gcovr_html_dir_provider.stamp],
                    commands=[
                        CMakeCommand("${CMAKE_COMMAND}", ["-E", "copy_directory", component_coverage_html_dir, component_variant_coverage_html_dir]),
                        CMakeCommand("${CMAKE_COMMAND}", ["-E", "touch", copy_done_stamp]),
                    ],
                )
            )
            copy_stamps.append(copy_done_stamp)

        unit_files = [coverage_file for name, files in component_files.items() if not components[name].integrates for coverage_file in files]
        integration_files = [coverage_file for name, files in component_files.items() if components[name].integrates for coverage_file in files]
        if unit_files:
            elements.extend(
                self._merged_coverage(
                    UserRequest(UserRequestScope.VARIANT, target=UserRequestTarget.COVERAGE),
                    "Generate coverage report for the variant",
                    "Generate variant coverage report",
                    variant_reports_dir,
                    gcovr_html_dir,
                    unit_files,
                    # It writes into the variant coverage reports directory, like the copies
                    [gcovr_html_dir_provider.stamp],
                    ["component", "merged", "coverage"],
                )
            )
        # A component can sit in several containers; gcovr would count it twice
        all_containers_files = list({str(coverage_file.json_report): coverage_file for coverage_file in [*container_files, *integration_files]}.values())
        if all_containers_files:
            elements.extend(
                self._merged_coverage(
                    UserRequest(UserRequestScope.VARIANT, target="all_containers_coverage"),
                    "Merge coverage for all containers",
                    "Generate coverage report for all containers",
                    variant_reports_dir,
                    variant_reports_dir.joinpath("all_containers_coverage"),
                    all_containers_files,
                    [],
                    ["container", "merged", "coverage"],
                )
            )
        if coverage_files:
            overall_target = UserRequest(UserRequestScope.VARIANT, target="overall_coverage")
            elements.extend(
                self._merged_coverage(
                    overall_target,
                    "Merge coverage for everything",
                    "Generate coverage report for everything",
                    variant_reports_dir,
                    variant_reports_dir.joinpath("overall_coverage"),
                    coverage_files,
                    # The copies run with the overall report: every copied report has a tracefile that it reads, so it exists whenever a copy does
                    copy_stamps,
                    ["overall", "coverage"],
                )
            )
            # copy_directory populates these dirs with files unknown to ninja
            elements.append(CMakeAddTargetCleanFiles(target=overall_target.target_name, files=[*component_variant_coverage_html_dirs]))
        return elements

    def _merged_coverage(
        self,
        target: UserRequest,
        description: str,
        target_description: str,
        reports_dir: CMakePath,
        html_dir: CMakePath,
        coverage_files: list[CoverageRelevantFile],
        depends: list[CMakePath],
        tags: list[str],
    ) -> list[CMakeElement]:
        """The merge reads only tracefiles, so it needs no object files and no gcovr config."""
        html_file = html_dir.joinpath("index.html")
        tracefiles = [coverage_file.json_report for coverage_file in coverage_files]
        coverage_cmd = CMakeCustomCommand(
            description=description,
            outputs=[html_file],
            depends=[*depends, *tracefiles],
            commands=[
                CMakeCommand("${CMAKE_COMMAND}", ["-E", "make_directory", html_dir]),
                CMakeCommand(
                    "gcovr",
                    [
                        "--root",
                        CMakePath(self.execution_context.project_root_dir),
                        *[argument for tracefile in tracefiles for argument in ("--add-tracefile", tracefile)],
                        "--html-nested",
                        "--html-theme",
                        "boost.blue",
                        "--output",
                        html_file,
                    ],
                ),
            ],
        )
        # The link is relative to the reports dir, the folder the page lands in when the report builds
        index_html = html_file.to_path().relative_to(reports_dir.to_path()).as_posix()
        page_dir = self.output_dir / target.component_name if target.component_name else self.output_dir
        page = page_dir / f"{target.target_name}.md"
        GeneratedFile(page, f"# Coverage\n\n## gcovr\n\n```{{toctree}}\n:maxdepth: 1\n\ngcovr report <./{index_html}#http://>\n```\n").to_file()
        self.execution_context.data_registry.insert(
            ReportRelevantFiles(
                target=target,
                files_to_be_included=[page],
                file_type=ReportRelevantFileType.COVERAGE_RESULT,
                tags=[*tags, "gcovr", *sorted({coverage_file.framework for coverage_file in coverage_files})],
            ),
            target.target_name,
        )
        return [
            coverage_cmd,
            CMakeCustomTarget(name=target.target_name, description=target_description, commands=[], depends=[html_file]),
            # gcovr --html-nested populates the dir with files unknown to ninja.
            # Register it for recursive removal on `clean` to avoid "Directory not empty" failures.
            CMakeAddTargetCleanFiles(target=target.target_name, files=[html_dir]),
        ]
