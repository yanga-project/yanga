from pathlib import Path
from typing import Any

from yanga_core.domain.components import Component
from yanga_core.domain.execution_context import ExecutionContext, UserRequest, UserRequestScope, UserRequestTarget
from yanga_core.domain.reports import ReportRelevantFiles, ReportRelevantFileType, ReportRelevantHtmlContent

from yanga.cmake.artifacts_locator import BuildArtifact, CMakeArtifactsLocator
from yanga.cmake.cmake_backend import CMakeAddTargetCleanFiles, CMakeCommand, CMakeComment, CMakeCustomCommand, CMakeCustomTarget, CMakeElement, CMakePath
from yanga.cmake.generator import CMakeGenerator, report_level, subcomponent_names


class ClangTidyCMakeGenerator(CMakeGenerator):
    """Run clang-tidy once per source file, so CMake reruns only the files that changed, and report per component and variant."""

    def __init__(
        self,
        execution_context: ExecutionContext,
        output_dir: Path,
        config: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(execution_context, output_dir, config)
        self.artifacts_locator = CMakeArtifactsLocator(output_dir, execution_context.spl_paths)
        self.clang_compile_commands_dir = self.artifacts_locator.cmake_build_dir.joinpath("clang_tidy")
        self.clang_compile_commands_file = self.clang_compile_commands_dir.joinpath("compile_commands.json")
        # A changed check selection must rerun the analysis. Only the project root file is tracked, not nested ones.
        config_file = execution_context.project_root_dir / ".clang-tidy"
        self.config_dependencies = [CMakePath(config_file)] if config_file.is_file() else []

    def generate(self) -> list[CMakeElement]:
        elements: list[CMakeElement] = [CMakeComment(f"Generated by {self.__class__.__name__}"), self._create_clang_compile_commands()]
        all_outputs: list[CMakePath] = []
        # An integration component is a container, so only the outputs of plain components make the all components report
        all_component_outputs: list[CMakePath] = []
        outputs_by_component: dict[str, list[CMakePath]] = {}
        copy_stamps: list[CMakePath] = []
        copied_dirs: list[str | CMakePath] = []
        # A component can sit in several containers; it is reported once over all containers
        all_container_outputs: dict[str, CMakePath] = {}
        for component in self.execution_context.components:
            # Containers and integration components that declare no production source have no own sources.
            # The files an integration component integrates are analysed under their own component.
            if not component.own_sources:
                continue
            commands = [self._create_clang_tidy_command(component, source) for source in component.own_sources]
            elements.extend(commands)
            component_outputs = [output for command in commands for output in command.outputs or []]
            all_outputs.extend(component_outputs)
            if report_level(component) == "component":
                all_component_outputs.extend(component_outputs)
            outputs_by_component[component.name] = component_outputs
            # An integration component is a container level result, like its coverage
            if component.integrates:
                all_container_outputs.update({str(output): output for output in component_outputs})
            elements.extend(self._create_component_report(component, component_outputs))
            copy_command = self._create_component_report_copy(component)
            elements.append(copy_command)
            copy_stamps.extend(copy_command.outputs or [])
            copied_dirs.append(self._get_variant_copy_dir(component.name))
        # A container merges the findings of its subcomponents
        for container in (component for component in self.execution_context.components if component.is_container):
            container_outputs = [output for name in subcomponent_names(container) for output in outputs_by_component.get(name, [])]
            if not container_outputs:
                continue
            all_container_outputs.update({str(output): output for output in container_outputs})
            elements.extend(self._create_component_report(container, container_outputs))
            copy_command = self._create_component_report_copy(container)
            elements.append(copy_command)
            copy_stamps.extend(copy_command.outputs or [])
            copied_dirs.append(self._get_variant_copy_dir(container.name))
        if all_container_outputs:
            elements.extend(self._create_all_containers_report(list(all_container_outputs.values())))
        if all_component_outputs:
            elements.extend(self._create_variant_report(all_component_outputs))
        if all_outputs:
            elements.extend(self._create_overall_report(all_outputs, copy_stamps, copied_dirs))
        return elements

    def _create_clang_compile_commands(self) -> CMakeCustomCommand:
        compile_commands_file = self.artifacts_locator.get_build_artifact(BuildArtifact.COMPILE_COMMANDS)
        return CMakeCustomCommand(
            description="Rewrite the compilation database for clang-tidy",
            outputs=[self.clang_compile_commands_file],
            depends=[compile_commands_file],
            commands=[
                CMakeCommand(
                    "yanga_cmd",
                    ["clang_compile_commands", "--compilation-database", compile_commands_file, "--output-file", self.clang_compile_commands_file],
                )
            ],
        )

    def _create_clang_tidy_command(self, component: Component, source: Path) -> CMakeCustomCommand:
        relative_source = source.relative_to(component.path) if source.is_relative_to(component.path) else Path(source.name)
        output_file = self.artifacts_locator.get_component_build_dir(component.name).joinpath("clang_tidy").joinpath(f"{relative_source.as_posix()}.txt")
        include_arguments: list[str | CMakePath] = (
            ["--include-directories", *[CMakePath(directory) for directory in component.include_directories]] if component.include_directories else []
        )
        return CMakeCustomCommand(
            description=f"Run clang-tidy for {component.name} {relative_source.as_posix()}",
            outputs=[output_file],
            depends=[CMakePath(source), self.clang_compile_commands_file, *self.config_dependencies],
            commands=[
                CMakeCommand(
                    "yanga_cmd",
                    [
                        "clang_tidy",
                        "--source-file",
                        CMakePath(source),
                        "--compilation-database-dir",
                        self.clang_compile_commands_dir,
                        "--output-file",
                        output_file,
                        *include_arguments,
                    ],
                )
            ],
        )

    def _create_report(
        self,
        lint_target: UserRequest,
        target_description: str,
        scope: str,
        input_files: list[CMakePath],
        reports_dir: CMakePath,
        output_dir: CMakePath,
        copy_stamps: list[CMakePath],
        tags: list[str],
    ) -> list[CMakeElement]:
        index_html = output_dir.joinpath("index.html")
        # When registering an html content, the path shall be relative to the reports directory
        self.execution_context.data_registry.insert(
            ReportRelevantFiles(
                target=lint_target,
                file_type=ReportRelevantFileType.HTML,
                files_to_be_included=[],
                html_content=ReportRelevantHtmlContent(name="Static Analysis", index_html=index_html.to_path().relative_to(reports_dir.to_path())),
                tags=tags,
            ),
            lint_target.target_name,
        )
        return [
            CMakeCustomCommand(
                description=f"Create clang-tidy report for {scope}",
                outputs=[index_html],
                depends=input_files,
                commands=[
                    CMakeCommand(
                        "yanga_cmd",
                        [
                            "clang_tidy_report",
                            "--input-files",
                            *input_files,
                            "--output-dir",
                            output_dir,
                            "--project-dir",
                            CMakePath(self.execution_context.project_root_dir),
                        ],
                    )
                ],
            ),
            CMakeCustomTarget(lint_target.target_name, target_description, [], [index_html, *copy_stamps]),
            # The report command writes pages unknown to ninja. Register the directory for recursive removal on `clean`.
            CMakeAddTargetCleanFiles(target=lint_target.target_name, files=[output_dir]),
        ]

    def _create_component_report(self, component: Component, input_files: list[CMakePath]) -> list[CMakeElement]:
        lint_target = UserRequest(UserRequestScope.COMPONENT, component_name=component.name, target=UserRequestTarget.LINT)
        reports_dir = self.artifacts_locator.get_component_reports_dir(component.name)
        output_dir = reports_dir.joinpath(self._get_component_report_relative_dir(component.name))
        level = report_level(component)
        tags = [level, component.name, "static-analysis"]
        return self._create_report(lint_target, f"Lint the {component.name} {level}", f"{level} {component.name}", input_files, reports_dir, output_dir, [], tags)

    def _create_all_containers_report(self, input_files: list[CMakePath]) -> list[CMakeElement]:
        lint_target = UserRequest(UserRequestScope.VARIANT, target="all_containers_lint")
        reports_dir = self.artifacts_locator.cmake_variant_reports_dir
        tags = ["container", "merged", "static-analysis"]
        return self._create_report(lint_target, "Lint all containers", "all containers", input_files, reports_dir, reports_dir.joinpath("all_containers_clang_tidy"), [], tags)

    @staticmethod
    def _get_component_report_relative_dir(component_name: str) -> str:
        """One folder per component, the same in the component and the variant reports, so the component page does not open the variant report."""
        return f"clang_tidy/{component_name}"

    def _get_variant_copy_dir(self, component_name: str) -> CMakePath:
        return self.artifacts_locator.cmake_variant_reports_dir.joinpath(self._get_component_report_relative_dir(component_name))

    def _create_component_report_copy(self, component: Component) -> CMakeCustomCommand:
        source_dir = self.artifacts_locator.get_component_reports_dir(component.name).joinpath(self._get_component_report_relative_dir(component.name))
        target_dir = self._get_variant_copy_dir(component.name)
        # copy_directory has no canonical file output, so the tracked output is a stamp we touch ourselves.
        copy_done_stamp = target_dir.joinpath(".yanga.stamp")
        return CMakeCustomCommand(
            description=f"Copy clang-tidy report for component {component.name} to variant report directory",
            outputs=[copy_done_stamp],
            # The report file, not the lint target: a target name gives only an order-only dependency, and the copy would go stale.
            depends=[source_dir.joinpath("index.html")],
            commands=[
                CMakeCommand("${CMAKE_COMMAND}", ["-E", "copy_directory", source_dir, target_dir]),
                CMakeCommand("${CMAKE_COMMAND}", ["-E", "touch", copy_done_stamp]),
            ],
        )

    def _create_variant_report(self, input_files: list[CMakePath]) -> list[CMakeElement]:
        lint_target = UserRequest(UserRequestScope.VARIANT, target=UserRequestTarget.LINT)
        reports_dir = self.artifacts_locator.cmake_variant_reports_dir
        tags = ["component", "merged", "static-analysis"]
        return self._create_report(lint_target, "Lint all components", "all components", input_files, reports_dir, reports_dir.joinpath("clang_tidy"), [], tags)

    def _create_overall_report(self, input_files: list[CMakePath], copy_stamps: list[CMakePath], copied_dirs: list[str | CMakePath]) -> list[CMakeElement]:
        lint_target = UserRequest(UserRequestScope.VARIANT, target="overall_lint")
        reports_dir = self.artifacts_locator.cmake_variant_reports_dir
        tags = ["overall", "static-analysis"]
        # The copies run with the overall report: every copied report reads outputs that the overall report reads too
        output_dir = reports_dir.joinpath("overall_clang_tidy")
        elements = self._create_report(lint_target, "Lint the entire variant", "the variant", input_files, reports_dir, output_dir, copy_stamps, tags)
        # copy_directory populates these dirs with files unknown to ninja, and `lint` that owns their parent may not exist
        elements.append(CMakeAddTargetCleanFiles(target=lint_target.target_name, files=copied_dirs))
        return elements
