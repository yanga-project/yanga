from pathlib import Path
from typing import Any

from yanga_core.domain.components import Component
from yanga_core.domain.execution_context import ExecutionContext, UserRequest, UserRequestScope, UserRequestTarget
from yanga_core.domain.reports import ReportRelevantFiles, ReportRelevantFileType

from yanga.cmake.artifacts_locator import BuildArtifact, CMakeArtifactsLocator
from yanga.cmake.cmake_backend import CMakeCommand, CMakeComment, CMakeCustomCommand, CMakeCustomTarget, CMakeElement, CMakePath
from yanga.cmake.generator import CMakeGenerator


class ClangTidyCMakeGenerator(CMakeGenerator):
    """Run clang-tidy once per source file, so CMake reruns only the files that changed, and report per component and variant."""

    def __init__(
        self,
        execution_context: ExecutionContext,
        output_dir: Path,
        config: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(execution_context, output_dir, config)
        self.artifacts_locator = CMakeArtifactsLocator(output_dir, execution_context.spl_paths)
        self.clang_compile_commands_dir = self.artifacts_locator.cmake_build_dir.joinpath("clang_tidy")
        self.clang_compile_commands_file = self.clang_compile_commands_dir.joinpath("compile_commands.json")
        # A changed check selection must rerun the analysis. Only the project root file is tracked, not nested ones.
        config_file = execution_context.project_root_dir / ".clang-tidy"
        self.config_dependencies = [CMakePath(config_file)] if config_file.is_file() else []

    def generate(self) -> list[CMakeElement]:
        elements: list[CMakeElement] = [CMakeComment(f"Generated by {self.__class__.__name__}"), self._create_clang_compile_commands()]
        all_outputs: list[CMakePath] = []
        for component in self.execution_context.components:
            # Container components have no sources of their own
            if not component.sources:
                continue
            commands = [self._create_clang_tidy_command(component, source) for source in component.sources]
            elements.extend(commands)
            component_outputs = [output for command in commands for output in command.outputs or []]
            all_outputs.extend(component_outputs)
            elements.extend(self._create_component_report(component, component_outputs))
        elements.extend(self._create_variant_report(all_outputs))
        return elements

    def _create_clang_compile_commands(self) -> CMakeCustomCommand:
        compile_commands_file = self.artifacts_locator.get_build_artifact(BuildArtifact.COMPILE_COMMANDS)
        return CMakeCustomCommand(
            description="Rewrite the compilation database for clang-tidy",
            outputs=[self.clang_compile_commands_file],
            depends=[compile_commands_file],
            commands=[
                CMakeCommand(
                    "yanga_cmd",
                    ["clang_compile_commands", "--compilation-database", compile_commands_file, "--output-file", self.clang_compile_commands_file],
                )
            ],
        )

    def _create_clang_tidy_command(self, component: Component, source: Path) -> CMakeCustomCommand:
        relative_source = source.relative_to(component.path) if source.is_relative_to(component.path) else Path(source.name)
        output_file = self.artifacts_locator.get_component_build_dir(component.name).joinpath("clang_tidy").joinpath(f"{relative_source.as_posix()}.txt")
        include_arguments: list[str | CMakePath] = (
            ["--include-directories", *[CMakePath(directory) for directory in component.include_directories]] if component.include_directories else []
        )
        return CMakeCustomCommand(
            description=f"Run clang-tidy for {component.name} {relative_source.as_posix()}",
            outputs=[output_file],
            depends=[CMakePath(source), self.clang_compile_commands_file, *self.config_dependencies],
            commands=[
                CMakeCommand(
                    "yanga_cmd",
                    [
                        "clang_tidy",
                        "--source-file",
                        CMakePath(source),
                        "--compilation-database-dir",
                        self.clang_compile_commands_dir,
                        "--output-file",
                        output_file,
                        *include_arguments,
                    ],
                )
            ],
        )

    def _create_report_command(self, description: str, input_files: list[CMakePath], report_file: CMakePath) -> CMakeCustomCommand:
        return CMakeCustomCommand(
            description=description,
            outputs=[report_file],
            depends=input_files,
            commands=[
                CMakeCommand(
                    "yanga_cmd",
                    [
                        "clang_tidy_report",
                        "--input-files",
                        *input_files,
                        "--output-file",
                        report_file,
                        "--project-dir",
                        CMakePath(self.execution_context.project_root_dir),
                    ],
                )
            ],
        )

    def _create_component_report(self, component: Component, input_files: list[CMakePath]) -> list[CMakeElement]:
        report_file = self.artifacts_locator.get_component_build_dir(component.name).joinpath("clang_tidy_report.md")
        lint_target = UserRequest(UserRequestScope.COMPONENT, component_name=component.name, target=UserRequestTarget.LINT)
        self.execution_context.data_registry.insert(
            ReportRelevantFiles(target=lint_target, files_to_be_included=[report_file.to_path()], file_type=ReportRelevantFileType.LINT_RESULT),
            lint_target.target_name,
        )
        return [
            self._create_report_command(f"Create clang-tidy report for component {component.name}", input_files, report_file),
            CMakeCustomTarget(lint_target.target_name, f"Lint the {component.name} component", [], [report_file]),
        ]

    def _create_variant_report(self, input_files: list[CMakePath]) -> list[CMakeElement]:
        report_file = self.artifacts_locator.cmake_build_dir.joinpath("clang_tidy_report.md")
        return [
            self._create_report_command("Create clang-tidy report for the variant", input_files, report_file),
            CMakeCustomTarget(UserRequest(UserRequestScope.VARIANT, target=UserRequestTarget.LINT).target_name, "Lint the entire variant", [], [report_file]),
        ]
