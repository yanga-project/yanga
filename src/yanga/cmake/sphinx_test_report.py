import re
from dataclasses import dataclass

from yanga_core.domain.execution_context import UserRequest
from yanga_core.domain.generated_file import GeneratedFile
from yanga_core.domain.reports import ReportRelevantFiles, ReportRelevantFileType

from .cmake_backend import CMakeComment, CMakeElement, CMakePath
from .generator import CMakeGenerator


@dataclass
class TestResultFile:
    """Used to register a component JUnit report for the generators that render it."""

    __test__ = False  # not a pytest test class

    target: UserRequest
    junit_report: CMakePath


class SphinxTestReportCMakeGenerator(CMakeGenerator):
    """
    Write a `Test Report` page per component JUnit report, for sphinx-test-reports.

    The page only points at the XML, so it is written at generation time; it is registered with the
    target that produces the XML, so the component report runs the tests first.
    Place it before the `ReportCMakeGenerator` in the platform generators.
    """

    def generate(self) -> list[CMakeElement]:
        for test_result in self.execution_context.data_registry.find_data(TestResultFile):
            component_name = test_result.target.component_name or ""
            junit_report = test_result.junit_report.to_path()
            page = junit_report.with_name(f"{component_name}_test_report.rst")
            report_id = "TR_" + re.sub(r"\W", "_", component_name).upper()
            GeneratedFile(
                page,
                f"Test Report\n===========\n\n.. test-report:: {component_name} test results\n   :id: {report_id}\n   :file: {junit_report.as_posix()}\n",
            ).to_file()
            self.execution_context.data_registry.insert(
                ReportRelevantFiles(target=test_result.target, files_to_be_included=[page], file_type=ReportRelevantFileType.TEST_RESULT),
                test_result.target.target_name,
            )
        return [CMakeComment(f"Generated by {self.__class__.__name__}")]
