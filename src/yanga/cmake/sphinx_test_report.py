import re
from dataclasses import dataclass, field
from pathlib import Path

from yanga_core.domain.execution_context import UserRequest, UserRequestScope, UserRequestTarget
from yanga_core.domain.generated_file import GeneratedFile
from yanga_core.domain.reports import ReportRelevantFiles, ReportRelevantFileType

from .cmake_backend import CMakeComment, CMakeCustomTarget, CMakeElement, CMakePath
from .generator import CMakeGenerator, report_level, subcomponent_names


@dataclass
class TestResultFile:
    """Used to register a component or variant JUnit report for the generators that render it."""

    __test__ = False  # not a pytest test class

    target: UserRequest
    junit_report: CMakePath
    #: The test sources the framework built, listed in the component report
    test_sources: list[Path] = field(default_factory=list)


#: The heading of every generated test page; the chapter that includes it gives the level
TITLE = "Test Results"


class SphinxTestReportCMakeGenerator(CMakeGenerator):
    """
    Write a `Test Results` page per component JUnit report, for sphinx-test-reports, and merged pages per container and over the variant.

    The pages only point at the XML, so they are written at generation time; each is registered with the
    targets that produce the XML, so the report runs the tests first.
    Place it before the `ReportCMakeGenerator` in the platform generators.
    """

    def generate(self) -> list[CMakeElement]:
        elements: list[CMakeElement] = [CMakeComment(f"Generated by {self.__class__.__name__}")]
        test_results = list(self.execution_context.data_registry.find_data(TestResultFile))
        for test_result in test_results:
            name = self._name(test_result)
            page = test_result.junit_report.to_path().with_name(f"{name}_test_report.rst")
            GeneratedFile(page, f"{TITLE}\n{'=' * len(TITLE)}\n\n{self._test_report(test_result, name)}").to_file()
            self.execution_context.data_registry.insert(
                ReportRelevantFiles(target=test_result.target, files_to_be_included=[page], file_type=ReportRelevantFileType.TEST_RESULT, tags=self._tags(test_result)),
                test_result.target.target_name,
            )

        containers = [component for component in self.execution_context.components if component.is_container]
        container_members = {container.name: subcomponent_names(container) for container in containers}
        for container in containers:
            container_results = [test_result for test_result in test_results if test_result.target.component_name in container_members[container.name]]
            target = UserRequest(UserRequestScope.COMPONENT, component_name=container.name, target=UserRequestTarget.TEST)
            page = self.output_dir / container.name / f"{container.name}_test_report.rst"
            self._write_merged_page(page, container.name, container_results, target, ["container", container.name, "test"])

        in_containers = {name for names in container_members.values() for name in names}
        component_results = [test_result for test_result in test_results if "component" in self._tags(test_result)]
        container_results = [test_result for test_result in test_results if "container" in self._tags(test_result) or test_result.target.component_name in in_containers]
        for page_name, results, tags in [
            ("all_components", component_results, ["component", "merged", "test"]),
            ("all_containers", container_results, ["container", "merged", "test"]),
            ("overall", test_results, ["overall", "test"]),
        ]:
            target = UserRequest(UserRequestScope.VARIANT, target=f"{page_name}_test")
            if self._write_merged_page(self.output_dir / f"{target.target_name}_report.rst", page_name, results, target, tags):
                description = f"Run the tests of the {page_name.replace('_', ' ')} test results page"
                elements.append(CMakeCustomTarget(target.target_name, description, [], [test_result.target.target_name for test_result in results]))
        return elements

    def _write_merged_page(self, page: Path, page_name: str, test_results: list[TestResultFile], target: UserRequest, tags: list[str]) -> bool:
        """A level with no JUnit file gets no page; the page name in each report id keeps the needs distinct when a file is on several pages."""
        if not test_results:
            return False
        sections = []
        for test_result in test_results:
            name = self._name(test_result)
            # A double underscore joins page and test, so a merged id differs from a component's own TR_<NAME>
            sections.append(f"{name}\n{'-' * len(name)}\n\n{self._test_report(test_result, f'{page_name}__{name}')}")
        GeneratedFile(page, f"{TITLE}\n{'=' * len(TITLE)}\n\n" + "\n".join(sections)).to_file()
        self.execution_context.data_registry.insert(
            ReportRelevantFiles(target=target, files_to_be_included=[page], file_type=ReportRelevantFileType.TEST_RESULT, tags=tags),
            target.target_name,
        )
        return True

    def _test_report(self, test_result: TestResultFile, id_name: str) -> str:
        # sphinx-test-reports derives the need ids from :id:, so it must be unique over all pages
        report_id = "TR_" + re.sub(r"\W", "_", id_name).upper()
        return f".. test-report:: {self._name(test_result)} test results\n   :id: {report_id}\n   :file: {self._junit_file(test_result)}\n   :collapse: false\n"

    def _name(self, test_result: TestResultFile) -> str:
        # A variant test has no component; it is named after the variant
        return test_result.target.component_name or self.execution_context.variant_name or ""

    def _junit_file(self, test_result: TestResultFile) -> str:
        # sphinx-test-reports joins a relative path onto tr_rootdir, by default the conf.py folder: the project dir the report builds from.
        junit_report = test_result.junit_report.to_path()
        project_root = self.execution_context.project_root_dir
        return (junit_report.relative_to(project_root) if junit_report.is_relative_to(project_root) else junit_report).as_posix()

    def _tags(self, test_result: TestResultFile) -> list[str]:
        name = test_result.target.component_name
        if name is None:
            return ["variant", "test"]
        component = next((component for component in self.execution_context.components if component.name == name), None)
        return [report_level(component) if component else "component", name, "test"]
